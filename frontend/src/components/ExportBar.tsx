// src/components/ExportBar.tsx
import { FileJson, Globe, Copy } from 'lucide-react';
import { getExportUrl } from '../api';

interface ExportBarProps {
  runId: string;
  capsule: object;
}

export function ExportBar({ runId, capsule }: ExportBarProps) {
  const downloadJson = () => {
    const blob = new Blob([JSON.stringify(capsule, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = 'dependency_exit_capsule.json'; a.click();
    URL.revokeObjectURL(url);
  };

  const copyPRDesc = async () => {
    const c = capsule as Record<string, unknown>;
    const text = `## Dependency Exit Capsule\n\n${c.maintenance_problem_identified || ''}\n\n**Generated by Universal Maintenance Agent v1.1.0**`;
    await navigator.clipboard.writeText(text);
  };

  return (
    <div className="flex flex-wrap items-center gap-2 p-3 bg-[#161b22] border border-[#30363d] rounded-lg">
      <span className="text-xs text-gray-500 mr-1">Export:</span>

      <button onClick={downloadJson}
        className="flex items-center gap-1.5 px-3 py-1.5 bg-[#21262d] hover:bg-[#30363d] border border-[#30363d] rounded text-xs text-gray-300 transition-colors">
        <FileJson size={13} className="text-blue-400" /> JSON
      </button>

      <a href={getExportUrl(runId, 'html')} target="_blank" rel="noreferrer"
        className="flex items-center gap-1.5 px-3 py-1.5 bg-[#21262d] hover:bg-[#30363d] border border-[#30363d] rounded text-xs text-gray-300 transition-colors">
        <Globe size={13} className="text-emerald-400" /> Self-contained HTML
      </a>

      <button onClick={copyPRDesc}
        className="flex items-center gap-1.5 px-3 py-1.5 bg-[#21262d] hover:bg-[#30363d] border border-[#30363d] rounded text-xs text-gray-300 transition-colors">
        <Copy size={13} className="text-amber-400" /> Copy PR Description
      </button>
    </div>
  );
}
